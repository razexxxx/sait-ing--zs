// ── Post Creation ──
postImageInput.addEventListener('change', (e) => {
  const file = e.target.files[0];
  postImagePreview.innerHTML = '';
  postImageBase64 = null;

  if (!file) {
    postImagePreview.classList.remove('active');
    return;
  }

  postImagePreview.classList.remove('active');
  postError.textContent = '';
  if (!['image/jpeg', 'image/png'].includes(file.type) || !/\.(jpe?g|png)$/i.test(file.name)) {
    postError.textContent = t('Выберите изображение JPEG или PNG.');
    postImageInput.value = '';
    return;
  }
  if (file.size > 5 * 1024 * 1024) {
    postError.textContent = t('Размер изображения не должен превышать 5 МБ.');
    postImageInput.value = '';
    return;
  }

  const reader = new FileReader();
  reader.onload = (ev) => {
    if (postImageInput.files[0] !== file) return;
    postImageBase64 = ev.target.result;
    const img = document.createElement('img');
    img.src = postImageBase64;
    img.alt = t('Предпросмотр');
    postImagePreview.innerHTML = '';
    postImagePreview.appendChild(img);
    postImagePreview.classList.add('active');
  };
  reader.onerror = () => { postError.textContent = t('Не удалось прочитать изображение.'); };
  reader.readAsDataURL(file);
});

async function submitPost() {
  const title = postTitle.value.trim();
  const description = postDescription.value.trim();
  if (postImageInput.files.length && !postImageBase64) {
    postError.textContent = t('Дождитесь загрузки изображения.');
    return;
  }

  if (!title) {
    postError.textContent = t('Укажите название поста');
    return;
  }

  submitPostBtn.disabled = true;
  submitPostBtn.textContent = t('Публикация...');
  postError.textContent = '';

  try {
    const res = await fetch('/api/posts', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ title, description, image_base64: postImageBase64, image_name: postImageInput.files[0]?.name, language: document.getElementById('post-language').value })
    });

    const data = await res.json();

    if (res.ok) {
      postTitle.value = '';
      postDescription.value = '';
      postImageInput.value = '';
      postImagePreview.innerHTML = '';
      postImagePreview.classList.remove('active');
      postImageBase64 = null;
      updateFileLabel();
      loadPosts();
      if (currentUser?.role === 'admin') loadAdminPhotos();
    } else {
      postError.textContent = translatedError(data.error) || t('Ошибка публикации');
    }
  } catch (e) {
    postError.textContent = t('Ошибка сети. Попробуйте позже.');
  } finally {
    submitPostBtn.disabled = false;
    submitPostBtn.textContent = t('Опубликовать');
  }
}

