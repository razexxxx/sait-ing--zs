function formatDate(isoString) {
    const date = new Date(/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/.test(isoString) ? isoString.replace(' ', 'T') + 'Z' : isoString);
    return date.toLocaleString(currentLanguage === 'en' ? 'en-GB' : 'ru-RU', {
        day: '2-digit',
        month: '2-digit',
        year: 'numeric',
        hour: '2-digit',
        minute: '2-digit'
    });
}

function escapeHtml(text) {
    const div = document.createElement('div');
    div.textContent = text;
    return div.innerHTML.replaceAll('"', '&quot;').replaceAll("'", '&#39;');
}

function getCoordinates(latitudeInput, longitudeInput) {
    const latitude = latitudeInput.value.trim();
    const longitude = longitudeInput.value.trim();
    if (!latitude && !longitude) return { latitude: null, longitude: null };
    if (!latitude || !longitude) throw new Error(t('Введите обе координаты или оставьте оба поля пустыми.'));
    const lat = Number(latitude), lng = Number(longitude);
    if (!Number.isFinite(lat) || !Number.isFinite(lng) || lat < -90 || lat > 90 || lng < -180 || lng > 180) {
        throw new Error(t('Введите корректные координаты: широту от -90 до 90 и долготу от -180 до 180.'));
    }
    return { latitude: lat, longitude: lng };
}

function formatLikes(count) {
    const number = Number(count) || 0;
    if (currentLanguage === 'en') return `${number} ${number === 1 ? 'like' : 'likes'}`;
    const lastTwo = number % 100, last = number % 10;
    const word = lastTwo > 10 && lastTwo < 20 ? 'лайков' : last === 1 ? 'лайк' : last > 1 && last < 5 ? 'лайка' : 'лайков';
    return `${number} ${word}`;
}

function postUrl(postId) {
    const origin = typeof location !== 'undefined' && location.origin && location.origin !== 'null' ? location.origin : '';
    return `${origin}/#post-${postId}`;
}

function initMap() {
    const container = document.getElementById('places-map');
    if (!container || !window.L || placesMap) return;
    placesMap = window.L.map(container, { scrollWheelZoom: false }).setView([56.63, 47.89], 7);
    window.L.tileLayer('https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png', {
        maxZoom: 19, attribution: '&copy; OpenStreetMap contributors'
    }).addTo(placesMap);
    mapMarkers = window.L.layerGroup().addTo(placesMap);
}

function renderMap(posts) {
    const note = document.getElementById('map-note');
    if (!placesMap || !mapMarkers) { note.textContent = ''; return; }
    mapMarkers.clearLayers();
    const located = posts.filter(post => Number.isFinite(post.latitude) && Number.isFinite(post.longitude));
    note.textContent = located.length ? '' : t('На карте пока нет мест с координатами.');
    const bounds = [];
    located.forEach(post => {
        const marker = window.L.marker([post.latitude, post.longitude]).addTo(mapMarkers);
        const escapedTitle = escapeHtml(post.title);
        marker.bindPopup(`<strong lang="${post.language === 'en' ? 'en' : 'ru'}">${escapedTitle}</strong><br><a href="#post-${post.id}">${t('Открыть публикацию')}</a>`);
        bounds.push([post.latitude, post.longitude]);
    });
    if (bounds.length) placesMap.fitBounds(bounds, { padding: [28, 28], maxZoom: 13 });
}

