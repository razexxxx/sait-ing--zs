function t(key, parameters = {}) {
    const message = translations[currentLanguage][key] ?? key;
    return String(message).replace(/\{(\w+)\}/g, (match, name) => parameters[name] ?? match);
}
function translatedError(error) {
    if (!error) return '';
    const until = /^Ваш аккаунт заблокирован до (.+)\. Причина: ([\s\S]*)$/.exec(error);
    if (until) return t('Ваш аккаунт заблокирован до {date}. Причина: {reason}', { date: until[1], reason: until[2] });
    const permanent = /^Ваш аккаунт заблокирован навсегда\. Причина: ([\s\S]*)$/.exec(error);
    if (permanent) return t('Ваш аккаунт заблокирован навсегда. Причина: {reason}', { reason: permanent[1] });
    return t(error);
}
function applyTranslations(root = document) {
    root.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (key) element.textContent = t(key);
    });
    for (const attribute of ['placeholder', 'aria-label']) {
        root.querySelectorAll(`[data-i18n-${attribute}]`).forEach(element => {
            element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
        });
    }
}
