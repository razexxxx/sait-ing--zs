function setLanguage(language, persist = true) {
    if (!['ru', 'en'].includes(language)) return;
    const previous = currentLanguage;
    currentLanguage = language;
    if (persist) { try { localStorage.setItem('mari-language', language); } catch {} }
    document.documentElement.lang = language;
    applyTranslations();
    document.querySelectorAll('[data-language]').forEach(button => {
        button.setAttribute('aria-pressed', String(button.dataset.language === language));
    });
    authBtn.textContent = t(currentUser ? 'Выйти' : 'Войти');
    currentUserRole.textContent = t(currentUser?.role === 'admin' ? 'Админ' : 'Пользователь');
    // Меняем только интерфейс, не значения полей и не тексты авторов.
    document.querySelectorAll('.login-error').forEach(element => {
        const key = Object.keys(translations[previous]).find(key => translations[previous][key] === element.textContent);
        if (key) element.textContent = t(key);
    });
    renderPosts(cachedPosts);
    renderPlaces(cachedPosts);
    renderComments(cachedComments);
    renderBans(cachedBans);
    renderAdminPhotos();
    updateTimeIndicator();
    updateFileLabel();
}
function updateFileLabel() {
    document.getElementById('post-file-name').textContent = postImageInput.files[0]?.name || t('Файл не выбран');
}
